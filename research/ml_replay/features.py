import numpy as np, pandas as pd
T0 = 1764460800; B = pd.Series(np.load('work/brti.npy')).ffill().to_numpy()
L = np.zeros(len(B)); L[1:] = np.diff(np.log(B))
c1 = np.concatenate([[0], np.cumsum(L)]); c2 = np.concatenate([[0], np.cumsum(L ** 2)])
def sd(end, w): a = end - w; s1 = c1[end] - c1[a]; s2 = c2[end] - c2[a]; return np.sqrt(np.maximum(s2 / w - (s1 / w) ** 2, 0))
S = pd.read_parquet('work/replay_scored.parquet')
e = (S.snap_ts.to_numpy() - T0).astype(np.int64)
for w in (10, 30, 60, 300, 900): S[f'ret_{w}'] = np.log(B[e] / B[e - w])
S['sig1'] = sd(e + 1, 60); S['sig5'] = sd(e + 1, 300)
S['vol_ratio'] = S.sig15 / S.sig60.clip(lower=1e-9); S['vol_ratio_short'] = S.sig1 / S.sig15.clip(lower=1e-9)
Teff = (S.secs_left - 40).clip(lower=1)
S['z'] = S.dist / (S.sig15.clip(lower=1e-7) * np.sqrt(Teff)); S['z60'] = S.dist / (S.sig60.clip(lower=1e-7) * np.sqrt(Teff))
# range position within the contract so far (high/low since open, at or before snap)
op = (S.open_ts.to_numpy() - T0).astype(np.int64)
hi = np.empty(len(S)); lo = np.empty(len(S))
for i, (a, b) in enumerate(zip(op, e)): seg = B[a:b + 1]; hi[i] = seg.max(); lo[i] = seg.min()
S['dist_hi'] = np.log(S.brti / hi); S['dist_lo'] = np.log(S.brti / lo)
S['strike_vs_prev'] = 0.0
S['hour_utc'] = pd.to_datetime(S.snap_ts, unit='s').dt.hour; S['dow'] = pd.to_datetime(S.snap_ts, unit='s').dt.dayofweek
S['log_cumvol'] = np.log1p(S.cumvol.fillna(0)); S['ask_age_c'] = S.ask_age.clip(upper=20); S['bid_age_c'] = S.bid_age.clip(upper=20)
S.to_parquet('work/features.parquet'); print(S.shape)
