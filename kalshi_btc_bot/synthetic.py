"""Synthetic data generator. FOR TESTING THE PIPELINE ONLY.

Produces btc.csv / markets.csv / quotes.csv in the same format as real data.
BTC follows a random walk with stochastic volatility and occasional sharp dips
and rebounds (so band breaches and golden crosses actually occur). Kalshi YES
quotes come from a simple probability model plus noise. P&L on this data says
nothing about the real strategy.
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np
import pandas as pd


def _norm_cdf(x):
    return 0.5 * (1 + np.vectorize(math.erf)(x / math.sqrt(2)))


def price_path(rng, n: int, start_price: float, rel_vol: float = 6e-5,
               dips_per_hour: float = 3.0) -> np.ndarray:
    """Random walk with stochastic volatility (per-second moves of roughly rel_vol * price)
    plus sharp dip-and-rebound events, so band breaches and golden crosses occur."""
    base = rel_vol * start_price
    vol = np.empty(n)
    v = 0.0
    for i in range(n):
        v = 0.999 * v + 0.045 * rng.standard_normal()
        vol[i] = base * math.exp(v)
    steps = vol * rng.standard_normal(n)
    k = min(int(n / 3600 * dips_per_hour), max(0, n - 400))
    for s in rng.choice(max(1, n - 400), size=k, replace=False):
        depth = rng.uniform(10, 42) * base
        down = rng.integers(20, 60)
        up = rng.integers(60, 240)
        steps[s:s + down] -= depth / down
        steps[s + down:s + down + up] += depth * rng.uniform(0.5, 1.4) / up
    return start_price + np.cumsum(steps)


def generate_linear(out_dir: str | Path, symbol: str, start_price: float, tick: float,
                    hours: float = 24, seed: int = 7, start: int = 1_798_761_600,
                    rel_vol: float = 3e-5) -> Path:
    """Synthetic 1-second price/bid/ask for a futures contract or ETF. TESTING ONLY."""
    rng = np.random.default_rng(seed)
    n = int(hours * 3600)
    px = price_path(rng, n, start_price, rel_vol)
    px = np.round(px / tick) * tick
    spread = tick * rng.choice([1, 1, 1, 2], size=n)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    pd.DataFrame({"timestamp": start + np.arange(n), "price": px.round(6),
                  "bid": (px - spread / 2).round(6), "ask": (px + spread / 2).round(6)}).to_csv(
        out / "price.csv", index=False)
    (out / "SYNTHETIC_DATA_README.txt").write_text(
        f"SYNTHETIC {symbol} data generated by kalshi_btc_bot.synthetic. Code testing only.\n")
    return out


def generate(out_dir: str | Path, hours: float = 24, seed: int = 7, start: int = 1_798_761_600,
             start_price: float = 100_000.0, market_seconds: int = 900) -> Path:
    rng = np.random.default_rng(seed)
    n = int(hours * 3600)
    n -= n % market_seconds
    t = start + np.arange(n)
    price = price_path(rng, n, start_price)
    # BRTI stand-in: spot plus small independent noise (real BRTI is a multi-exchange index).
    brti = price + rng.normal(0, 3.0, n)

    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    pd.DataFrame({"timestamp": t, "price": price.round(2), "brti": brti.round(2)}).to_csv(
        out / "btc.csv", index=False)

    markets, quotes = [], []
    sigma = float(np.std(np.diff(price)))
    for k in range(n // market_seconds):
        o = k * market_seconds
        c = o + market_seconds
        strike = round(float(brti[max(0, o - 60):o + 1].mean()), 2)
        ticker = f"SYNTH-BTC15M-{k:04d}"
        settle = float(brti[c - 60:c].mean())
        markets.append({"ticker": ticker, "open_time": t[o], "close_time": start + c,
                        "strike": strike, "result": "yes" if settle >= strike else "no"})
        last = None
        for i in range(o, c, 2):          # a quote snapshot every 2 seconds
            tau = max(c - i, 1)
            fair = float(_norm_cdf((price[i] - strike) / (sigma * math.sqrt(tau) + 1e-9)))
            fair = min(max(fair + rng.normal(0, 0.03), 0.02), 0.98)
            half = rng.choice([0.01, 0.01, 0.02, 0.03])
            bid = round(max(0.01, fair - half), 2)
            ask = round(min(0.99, fair + half), 2)
            if bid >= ask:
                bid = round(ask - 0.01, 2)
            if last is None or rng.random() < 0.3:
                last = round(min(max(fair + rng.normal(0, 0.01), 0.01), 0.99), 2)
            quotes.append({"timestamp": t[i], "ticker": ticker, "yes_bid": bid, "yes_ask": ask,
                           "yes_bid_size": int(rng.integers(20, 600)),
                           "yes_ask_size": int(rng.integers(20, 600)), "last_price": last})
    pd.DataFrame(markets).to_csv(out / "markets.csv", index=False)
    pd.DataFrame(quotes).to_csv(out / "quotes.csv", index=False)
    (out / "SYNTHETIC_DATA_README.txt").write_text(
        "This folder contains SYNTHETIC data generated by kalshi_btc_bot.synthetic.\n"
        "It is for testing the code only. Results on it are not evidence about the strategy.\n")
    return out
